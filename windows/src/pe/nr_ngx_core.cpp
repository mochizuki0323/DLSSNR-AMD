// One Session per API in this process, even if both of our DLLs are loaded.
//
// windows/src/pe/nr_dlssnr_model.cpp keeps one nr::pe::Session per graphics API, which is what stops a
// re-created feature from re-uploading 300 MB of weights. Both nvngx.dll_dlssnr.dll and _nvngx.dll
// link that translation unit, so a process holding BOTH would hold two of those singletons and build
// two networks on one GPU.
//
// It cannot be assumed away in either direction: wilsjo2 >= 0.8.1 loads no forwarder and tells users
// to delete it (INSTALL-DLSSNR.md:13), so this core must carry its own model; Dagherbou's release
// loads the forwarder and never touches CreateFeature. But a host could do both, and the answer is
// cheap -- if nvngx.dll_dlssnr.dll is already in the module list, route through its C exports, which
// are the same code driving the session it already owns. GetModuleHandleW, never LoadLibrary: the
// question is "is it already here", not "make it be here".
struct Forwarder {
    using PFN_create = void* (*)(const wchar_t*, const wchar_t*, ID3D12Device*, ID3D12GraphicsCommandList*,
                                 void*, unsigned int, unsigned int, int, float, int, float, float, float,
                                 int, int);
    using PFN_evaluate = int (*)(ID3D12GraphicsCommandList*, void*, void*, ID3D12Resource*, ID3D12Resource*,
                                 ID3D12Resource*, ID3D12Resource*, unsigned int, unsigned int, unsigned int,
                                 unsigned int, unsigned int, unsigned int, unsigned int, unsigned int,
                                 unsigned int, unsigned int, int, int, float, int, float, float, float, int,
                                 float, float);
    using PFN_release = void (*)(void*);
    using PFN_vk_init = int (*)(const wchar_t*, const wchar_t*, void*, void*, void*, int);
    using PFN_vk_create = void* (*)(void*, void*, unsigned int, unsigned int, int, float, int, float, float,
                                    float, int, int);
    using PFN_vk_evaluate = int (*)(void*, void*, void*, void*, void*, void*, void*, unsigned int,
                                    unsigned int, unsigned int, unsigned int, unsigned int, unsigned int,
                                    unsigned int, unsigned int, unsigned int, unsigned int, int, int, float,
                                    int, float, float, float, int, float, float);
    using PFN_vk_release = void (*)(void*);

    PFN_create create = nullptr;
    PFN_evaluate evaluate = nullptr;
    PFN_release release = nullptr;
    PFN_vk_init vk_init = nullptr;
    PFN_vk_create vk_create = nullptr;
    PFN_vk_evaluate vk_evaluate = nullptr;
    PFN_vk_release vk_release = nullptr;

    bool d3d12() const { return create && evaluate && release; }
    bool vulkan() const { return vk_init && vk_create && vk_evaluate && vk_release; }
};

const Forwarder& forwarder() {
    static Forwarder resolved = [] {
        Forwarder f;
        HMODULE m = GetModuleHandleW(L"nvngx.dll_dlssnr.dll");
        if (!m) return f;
        auto sym = [m](const char* n) { return reinterpret_cast<void*>(GetProcAddress(m, n)); };
        f.create = reinterpret_cast<Forwarder::PFN_create>(sym("dlssnr_call_create"));
        f.evaluate = reinterpret_cast<Forwarder::PFN_evaluate>(sym("dlssnr_call_evaluate_v2"));
        f.release = reinterpret_cast<Forwarder::PFN_release>(sym("dlssnr_call_release"));
        f.vk_init = reinterpret_cast<Forwarder::PFN_vk_init>(sym("dlssnr_vk_init"));
        f.vk_create = reinterpret_cast<Forwarder::PFN_vk_create>(sym("dlssnr_vk_create"));
        f.vk_evaluate = reinterpret_cast<Forwarder::PFN_vk_evaluate>(sym("dlssnr_vk_evaluate_v2"));
        f.vk_release = reinterpret_cast<Forwarder::PFN_vk_release>(sym("dlssnr_vk_release"));
        nr::pe::log("[nr] _nvngx.dll: nvngx.dll_dlssnr.dll is already loaded in this process; feature 18 "
                    "will run on its session rather than starting a second network (D3D12 %s, Vulkan %s)",
                    f.d3d12() ? "yes" : "no", f.vulkan() ? "yes" : "no");
        return f;
    }();
    return resolved;
}

// The Vulkan handles the game gave us at NVSDK_NGX_VULKAN_Init*. VULKAN_CreateFeature1 carries only the
// device, and the model needs the instance and the physical device too, so they are kept from init.
void* g_vk_instance = nullptr;
void* g_vk_physical = nullptr;
void* g_vk_device = nullptr;
bool g_vk_model_inited = false;

// Called from every NVSDK_NGX_VULKAN_Init* variant, all of which carry the three handles, with g_lock
// held. The model is initialised as soon as all three are known, so its "no queue is known" decline
// lands in the log at init -- where a user can act on it -- rather than at the first frame.
void note_vulkan(NrVkInstance instance, NrVkPhysicalDevice physical, NrVkDevice device) {
    if (instance) g_vk_instance = instance;
    if (physical) g_vk_physical = physical;
    if (device) g_vk_device = device;
    if (g_vk_model_inited || !g_vk_instance || !g_vk_physical || !g_vk_device) return;
    const Forwarder& fwd = forwarder();
    const int result = fwd.vulkan() ? fwd.vk_init(nullptr, nullptr, g_vk_instance, g_vk_physical,
                                                  g_vk_device, 0)
                                    : nr::dlssnr::vk_init(g_vk_instance, g_vk_physical, g_vk_device);
    g_vk_model_inited = result == static_cast<int>(NVSDK_NGX_Result_Success);
}

// VULKAN_CreateFeature1's own device, for the case where init declined and the handles have since
// become answerable (the queue watcher can learn a queue after NGX was initialised).
bool ensure_vulkan_model(NrVkDevice device) {
    std::lock_guard<std::mutex> guard(g_lock);
    if (g_vk_model_inited) return true;
    note_vulkan(nullptr, nullptr, device);
    return g_vk_model_inited;
}

// NVSDK_NGX_FeatureDiscoveryInfo's second field, read positionally so no SDK struct has to be
// declared here: { NVSDK_NGX_Version SDKVersion; NVSDK_NGX_Feature FeatureID; ... } and both are
// int-sized enums (external/nvngx_dlss_sdk/nvsdk_ngx_defs.h:490-497).
int discovery_feature_id(const void* info) {
    return info ? reinterpret_cast<const int*>(info)[1] : 0;
}

// NVSDK_NGX_FeatureRequirement is { NVSDK_NGX_Feature_Support_Result FeatureSupported; unsigned int
// MinHWArchitecture; char MinOSVersion[255]; } -- defs.h:499-509. Zero in the first field IS
// "Supported" (defs.h:402), so "supported, no minimum architecture, no minimum OS" is nine zero bytes.
void write_requirement(void* out, bool supported) {
    if (!out) return;
    auto* words = static_cast<unsigned int*>(out);
    words[0] = supported ? 0u : static_cast<unsigned int>(16);   // 16 = NotImplemented
    words[1] = 0u;
    static_cast<char*>(out)[8] = '\0';
}

