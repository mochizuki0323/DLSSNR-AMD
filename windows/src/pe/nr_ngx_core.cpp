// The capability defaults.
//
// These say "this core runs no features". The names are the ones NVIDIA's own capability block
// publishes and the ones OptiScaler reads back (NVNGX_Parameter.cpp InitNGXParameters uses the same
// macros: SuperSampling.Available, .NeedsUpdatedDriver, .MinDriverVersionMajor/Minor,
// .FeatureInitResult; the denoiser family is spelled SuperSamplingDenoising.*).
//
// They are also, on the path a game sees, overwritten a microsecond later -- see the DLSS gating note
// at the bottom. They matter for the path OptiScaler's *own* DLSS-NR code takes, which reads this
// block directly without calling InitNGXParameters on it first.
void populate_capabilities(Parameters* p) {
    p->set_uint("SuperSampling.Available", 0u);
    p->set_uint("SuperSampling.NeedsUpdatedDriver", 0u);
    p->set_uint("SuperSampling.MinDriverVersionMajor", 0u);
    p->set_uint("SuperSampling.MinDriverVersionMinor", 0u);
    p->set_uint("SuperSampling.FeatureInitResult",
           static_cast<unsigned int>(NVSDK_NGX_Result_FAIL_FeatureNotSupported));

    p->set_uint("SuperSamplingDenoising.Available", 0u);
    p->set_uint("SuperSamplingDenoising.NeedsUpdatedDriver", 0u);
    p->set_uint("SuperSamplingDenoising.MinDriverVersionMajor", 0u);
    p->set_uint("SuperSamplingDenoising.MinDriverVersionMinor", 0u);
    p->set_uint("SuperSamplingDenoising.FeatureInitResult",
           static_cast<unsigned int>(NVSDK_NGX_Result_FAIL_FeatureNotSupported));

    p->set_uint("FrameGeneration.Available", 0u);
    p->set_uint("FrameInterpolation.Available", 0u);

    p->set_uint("CreationNodeMask", 1u);
    p->set_uint("VisibilityNodeMask", 1u);

    // There is no DLSSNR.Available anywhere in OptiScaler -- nothing reads such a key, so nothing is
    // written for it. (grep -rn "DLSSNR.Available" over the reference tree: no hits.) Whether the NR
    // pass runs is decided by Config [DlssNr] Enabled plus the two DLLs being present, never by a
    // capability bit.
}

Parameters* new_block(bool capability) {
    auto* p = new Parameters();
    if (capability) populate_capabilities(p);
    return p;
}

