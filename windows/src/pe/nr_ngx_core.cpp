// Reading the block, which on this path is our own object.
//
// DlssNr_Proxy.cpp:154 takes the block from D3D12_GetCapabilityParameters, so the pointer handed to
// CreateFeature and EvaluateFeature is a Parameters* that left new_block() a moment earlier. It is
// recognised by its vtable pointer and read through std::map directly -- no call back out through the
// vtable and no chance of a slot mismatch on the way in. A block from anywhere else (a game's own, a
// future OptiScaler that allocates its own) is still read, through the published interface, which is
// correct because nr_ngx_abi.hpp lays that interface out in MSVC's order.
class Reader {
  public:
    explicit Reader(const NVSDK_NGX_Parameter* p)
        : block_(p), mine_(p && p->vtbl == &vt::kTable ? reinterpret_cast<const Parameters*>(p) : nullptr) {}

    bool valid() const { return block_ != nullptr; }
    bool is_ours() const { return mine_ != nullptr; }

    bool uint(const char* name, unsigned int* out) const {
        if (!block_) return false;
        return (mine_ ? mine_->get_uint(name, out) : block_->Get(name, out)) == NVSDK_NGX_Result_Success;
    }
    bool real(const char* name, float* out) const {
        if (!block_) return false;
        return (mine_ ? mine_->get_float(name, out) : block_->Get(name, out)) == NVSDK_NGX_Result_Success;
    }
    // Every resource in this surface is written either as Set(void*) (Vulkan, and OptiScaler's own
    // note that NVIDIA's table "ignores typed ID3D12Resource* setters") or as Set(ID3D12Resource*)
    // (the D3D12 path). Our block keeps both in one family, so one read answers both; a foreign block
    // is asked through the void* getter and then the resource getter.
    void* resource(const char* name) const {
        if (!block_) return nullptr;
        void* p = nullptr;
        if (mine_) return mine_->get_ptr(name, &p) == NVSDK_NGX_Result_Success ? p : nullptr;
        if (block_->Get(name, &p) == NVSDK_NGX_Result_Success) return p;
        ID3D12Resource* r = nullptr;
        if (block_->Get(name, &r) == NVSDK_NGX_Result_Success) return r;
        return nullptr;
    }

  private:
    const NVSDK_NGX_Parameter* block_;
    const Parameters* mine_;
};

// The six tuning controls, read over whatever the feature already holds so a key the caller left out
// keeps its create-time value. The reference writes all six at create AND at every evaluate
// (DlssNr_Proxy.cpp:67-72 and :272-277), so in practice every one is present every time.
//
// DLSSNR.SkinStructureStrength's -1 is "follow LocalStructure", not "off" -- DlssNr_Common.h:324 --
// and nr::Controls::skin_structure already means exactly that, so it passes through unmapped.
void read_controls(const Reader& r, nr::dlssnr::Controls6* c) {
    float f = 0.0f;
    unsigned int u = 0;
    if (r.real("DLSSNR.Intensity", &f)) c->intensity = f;
    if (r.uint("DLSSNR.Style", &u)) c->style = static_cast<int>(u);
    if (r.real("DLSSNR.LocalStructureStrength", &f)) c->local_structure = f;
    if (r.real("DLSSNR.LocalToneStrength", &f)) c->local_tone = f;
    if (r.real("DLSSNR.SkinStructureStrength", &f)) c->skin_structure = f;
    if (r.uint("DLSSNR.UseAutoMask", &u)) c->use_auto_mask = static_cast<int>(u);

    // Read and ignored, deliberately:
    //
    //   DLSSNR.GlobalToneStrength  the pinned DLL does not have it. A scan of nvngx_dlssnr.dll for
    //                              DLSSNR.* yields 61 names and this is not one of them
    //                              (DlssNr_Common.h:315-320), which is why wilsjo2 never writes it and
    //                              why the forwarder's dlssnr_call_set_extras drops it too.
    //   DLSSNR.UICorrection        our network has no UI-correction pass; the reference always writes
    //                              the model's own default 1u (DlssNr_Proxy.cpp:76).
    //   DLSSNR.ControlMask         always null on this path (:77); an external mask would take
    //                              precedence over UseAutoMask and there is never one to take.
    //   DLSSNR.UI / .UIAlpha / .Backbuffer and their twelve subrect keys -- all null and all zero
    //                              (:78-85). Nothing here has a UI pass to give them to.
}

